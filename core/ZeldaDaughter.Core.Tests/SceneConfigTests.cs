        [Fact]
        public void Prologue_distances_follow_the_design()
        {
            // §2: «через ~15 секунд ходьбы по дороге — крестьянин… город совсем рядом — в первые минуты».
            var c = SceneConfig.Parse(File.ReadAllText(Path.Combine(ScenesDir, "prologue-grey.json")));
            var walk = ZeldaDaughter.Core.Data.DataSet.Load(TestPaths.DataRoot).Movement.WalkSpeed;
            float Dist(string id)
            {
                var p = c.Objects.Single(o => o.Id == id).Position;
                return (float)System.Math.Sqrt((p.X - c.Hero.Spawn.X) * (p.X - c.Hero.Spawn.X) + (p.Z - c.Hero.Spawn.Z) * (p.Z - c.Hero.Spawn.Z));
            }
            Assert.InRange(Dist("npc_peasant") / walk, 13f, 17f);
            Assert.InRange(Dist("town_gate") / walk, 20f, 60f);
            foreach (var target in new[] { "town_gate", "town_square" }) Assert.Contains(c.Objects, o => o.Id == target);
        }

        // --- D-10: the start region (scenes/region.json, generated by tools/gen-region.py) ---

        static SceneConfig Region() => SceneConfig.Parse(File.ReadAllText(Path.Combine(ScenesDir, "region.json")));

        static float Walk() => ZeldaDaughter.Core.Data.DataSet.Load(TestPaths.DataRoot).Movement.WalkSpeed;

        /// <summary>Metres along the main road from its start to the point on it nearest to (x, z); lateral = distance to the road.</summary>
        static (float Along, float Lateral) OnRoad(SceneConfig c, float x, float z)
        {
            var pts = c.Paths.Single(p => p.Id == "road_main").Points;
            float best = float.MaxValue, bestAlong = 0, acc = 0;
            for (int i = 0; i + 1 < pts.Count; i++)
            {
                float vx = pts[i + 1].X - pts[i].X, vz = pts[i + 1].Z - pts[i].Z, len = (float)System.Math.Sqrt(vx * vx + vz * vz);
                float t = System.Math.Max(0f, System.Math.Min(1f, ((x - pts[i].X) * vx + (z - pts[i].Z) * vz) / (len * len)));
                float px = pts[i].X + vx * t - x, pz = pts[i].Z + vz * t - z, d = (float)System.Math.Sqrt(px * px + pz * pz);
                if (d < best) { best = d; bestAlong = acc + len * t; }
                acc += len;
            }
            return (bestAlong, best);
        }

        static float RoadLength(SceneConfig c) => OnRoad(c, 1e6f, 0f).Along;

        [Fact]
        public void Region_distances_follow_the_design()
        {
            // §2 «Пролог»: крестьянин ~15 с от спавна; город — в первые минуты; §2 «Размер»: край до края 2–3 мин.
            var c = Region();
            float walk = Walk();
            var peasant = c.Objects.Single(o => o.Id == "npc_peasant").Position;
            var spawn = c.Hero.Spawn;
            Assert.InRange((float)System.Math.Sqrt((peasant.X - spawn.X) * (peasant.X - spawn.X) + (peasant.Z - spawn.Z) * (peasant.Z - spawn.Z)) / walk, 13f, 17f);
            float peasantAlong = OnRoad(c, peasant.X, peasant.Z).Along, gate = OnRoad(c, 35f, 0f).Along;
            var gateObj = c.Objects.Single(o => o.Id == "town_gate").Position;
            gate = OnRoad(c, gateObj.X, gateObj.Z).Along;
            Assert.InRange((gate - peasantAlong) / walk, 20f, 75f);           // от крестьянина до ворот — не дольше ~75 с
            float far = c.Objects.Where(o => o.Tags.Contains("poi")).Max(o => o.Position.X);
            Assert.InRange(RoadLength(c) / walk, 120f, 180f);                 // дорога от спавна до дальнего края города
            Assert.True(far <= c.Ground.SizeX / 2);
            foreach (var target in new[] { "town_gate", "town_square", "anchor_bridge", "anchor_glade" }) Assert.Contains(c.Objects, o => o.Id == target);
            // лес и поляна — 15–20 с вглубь от дороги
            var glade = c.Objects.Single(o => o.Id == "anchor_glade").Position;
            var trail = c.Paths.Single(p => p.Id == "trail_glade").Points;
            float len = 0;
            for (int i = 0; i + 1 < trail.Count; i++) len += (float)System.Math.Sqrt((trail[i + 1].X - trail[i].X) * (trail[i + 1].X - trail[i].X) + (trail[i + 1].Z - trail[i].Z) * (trail[i + 1].Z - trail[i].Z));
            Assert.InRange(len / walk, 15f, 20f);
            Assert.True(OnRoad(c, glade.X, glade.Z).Lateral > 30f);
        }

        [Fact]
        public void Region_points_of_interest_every_15_seconds_along_the_road()
        {
            // критерий D-10 №2: соседние точки интереса (тег poi) вдоль главной дороги — не дальше 15 с × скорость шага.
            var c = Region();
            float limit = 15f * Walk();
            var stops = c.Objects.Where(o => o.Tags.Contains("poi")).Select(o => OnRoad(c, o.Position.X, o.Position.Z))
                .Where(a => a.Lateral <= 30f).Select(a => a.Along).OrderBy(a => a).ToList();
            Assert.True(stops.Count >= 20, $"точек интереса у дороги: {stops.Count}");
            stops.Insert(0, 0f);
            stops.Add(RoadLength(c));
            for (int i = 1; i < stops.Count; i++)
                Assert.True(stops[i] - stops[i - 1] <= limit, $"между точками интереса {stops[i - 1]:0.#} и {stops[i]:0.#} м — {(stops[i] - stops[i - 1]) / Walk():0.#} с (> 15)");
        }

