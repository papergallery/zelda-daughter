        [Fact]
        public void Region_keeps_the_road_and_the_bridge_free()
        {
            var c = Region();
            var cat = SceneLayoutTests.Catalog();
            var road = c.Paths.Single(p => p.Id == "road_main").Points;
            var samples = new System.Collections.Generic.List<(float X, float Z)>();
            for (int i = 0; i + 1 < road.Count; i++)
            {
                float vx = road[i + 1].X - road[i].X, vz = road[i + 1].Z - road[i].Z, len = (float)System.Math.Sqrt(vx * vx + vz * vz);
                for (float t = 0; t < len; t += 0.5f) samples.Add((road[i].X + vx * t / len, road[i].Z + vz * t / len));
            }
            foreach (var o in c.Objects.Where(o => !string.IsNullOrEmpty(o.Model) && o.Collide != false))
            {
                var def = cat.Get(o.Model!);
                if (def.Collider.Kind == "none" || def.IsComposite) continue;
                var b = cat.Bounds(o.Model!);
                double a = o.Rotation.Y * System.Math.PI / 180.0;
                float lx = b.CenterX * o.Scale.X, lz = b.CenterZ * o.Scale.Z;
                var rect = new Area { Shape = "rect", Center = new Pt(o.Position.X + lx * (float)System.Math.Cos(a) + lz * (float)System.Math.Sin(a), o.Position.Z - lx * (float)System.Math.Sin(a) + lz * (float)System.Math.Cos(a)),
                    Size = new Pt(b.SizeX * o.Scale.X, b.SizeZ * o.Scale.Z), Rotation = o.Rotation.Y };
                foreach (var s in samples) Assert.True(rect.SignedDistance(s.X, s.Z) > 0.5f, $"{o.Id} стоит на главной дороге у ({s.X:0.#}; {s.Z:0.#})");
            }
            foreach (var p in Scatterer.Generate(c, cat).Where(p => p.Collide))
                foreach (var s in samples) Assert.True((p.X - s.X) * (p.X - s.X) + (p.Z - s.Z) * (p.Z - s.Z) > 1.2f * 1.2f, $"{p.Id} ({p.ModelId}) на главной дороге у ({s.X:0.#}; {s.Z:0.#})");
        }

