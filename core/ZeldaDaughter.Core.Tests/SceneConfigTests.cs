        {
            var c = SceneConfig.Parse("{\"name\":\"t\",\"ground\":{\"sizeX\":10,\"sizeZ\":10},\"camera\":{\"pitch\":35,\"distance\":20,\"size\":8}," +
                "\"hero\":{\"shape\":\"capsule\"},\"objects\":[{\"id\":\"a\",\"shape\":\"cube\",\"position\":{\"x\":50}}," +
